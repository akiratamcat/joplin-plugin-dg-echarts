// Writes tests/manual/large-note.md: large charts for the stage 2 manual
// test of the drawing time (design 7.3, V-14). Run: node tests/manual/generate-large-note.cjs
const fs = require('fs');
const path = require('path');

// Repeatable pseudo-random values (no Math.random: the note must be the same every time).
const value = (i) => (i * 7919) % 1000;

function scatter(n) {
	return { title: { text: `Scatter, ${n} points` }, xAxis: {}, yAxis: {}, series: [{ type: 'scatter', symbolSize: 3, data: Array.from({ length: n }, (_, i) => [value(i), value(i + 1)]) }] };
}

function line(n) {
	return { title: { text: `Line, ${n} points` }, xAxis: { type: 'category' }, yAxis: {}, series: [{ type: 'line', showSymbol: false, data: Array.from({ length: n }, (_, i) => value(i)) }] };
}

function pie(n) {
	return { title: { text: `Pie, ${n} slices` }, series: [{ type: 'pie', data: Array.from({ length: n }, (_, i) => ({ name: `p${i}`, value: value(i) + 1 })) }] };
}

const charts = [
	['A small chart (edit its numbers to feel the typing delay with the large charts below)', { xAxis: { type: 'category', data: ['a', 'b', 'c'] }, yAxis: {}, series: [{ type: 'bar', data: [1, 3, 2] }] }],
	['Line, 10000 points', line(10000)],
	['Scatter, 2000 points', scatter(2000)],
	['Scatter, 10000 points', scatter(10000)],
	['Pie, 1000 slices', pie(1000)],
	['Pie, 5000 slices (about 143000 characters)', pie(5000)],
];

const parts = [
	'# dg-echarts stage 2: large charts (V-14)',
	'',
	'Generated by tests/manual/generate-large-note.cjs. The note waits while each chart is drawn.',
	'Charts that take 200 ms or more are reported in the developer tools (Help > Toggle development tools > Console, "dg-echarts: a chart of ... took ... ms").',
	'',
];
charts.forEach(([title, option], i) => {
	const json = JSON.stringify(option);
	parts.push(`## ${i + 1}. ${title} (${json.length} characters)`, '', '```echarts', json, '```', '');
});

const out = path.join(__dirname, 'large-note.md');
fs.writeFileSync(out, parts.join('\n'));
console.log(`${out}: ${fs.statSync(out).size} bytes`);
